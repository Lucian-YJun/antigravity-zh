function translateMenu(menu) {
    if (!menu || !menu.items) {
        return;
    }
    for (const item of menu.items) {
        const zh = MENU_LABELS[item.label];
        if (zh && item.label !== zh) {
            item.label = zh;
        }
        if (item.submenu) {
            translateMenu(item.submenu);
        }
    }
}
